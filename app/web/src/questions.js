// Pick n random questions not asked yet in this room.
export function pickQuestions(asked = [], n = 4) {
  const seen = new Set(asked.map((q) => q.trim().toLowerCase()));
  const pool = QUESTIONS.filter((q) => !seen.has(q.toLowerCase()));
  const src = pool.length >= n ? pool : QUESTIONS;
  return [...src].sort(() => Math.random() - 0.5).slice(0, n);
}
